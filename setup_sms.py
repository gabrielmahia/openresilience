#!/usr/bin/env python3
"""
OpenResilience SMS Alert Service - Interactive Setup Wizard

This script will guide you through the complete setup process.
Just run it and follow the prompts!
"""

import subprocess
import sys
import time


def print_header(text):
    """Print a nice header."""
    print("\n" + "=" * 70)
    print(f"  {text}")
    print("=" * 70)


def print_step(number, title):
    """Print a step header."""
    print(f"\n{'=' * 70}")
    print(f"STEP {number}: {title}")
    print("=" * 70)


def wait_for_user(prompt="Press ENTER to continue..."):
    """Wait for user to press enter."""
    input(f"\n{prompt}")


def check_python():
    """Check Python version."""
    version = sys.version_info
    if version.major < 3 or (version.major == 3 and version.minor < 7):
        print(f"❌ Python {version.major}.{version.minor} is too old!")
        print("   Please install Python 3.7 or higher")
        return False
    print(f"✅ Python {version.major}.{version.minor}.{version.micro}")
    return True


def check_pip():
    """Check if pip is installed."""
    try:
        subprocess.run(['pip', '--version'], capture_output=True, check=True)
        print("✅ pip is installed")
        return True
    except:
        print("❌ pip not found!")
        print("   Install with: python -m ensurepip")
        return False


def install_dependencies():
    """Install required packages."""
    packages = [
        'africastalking',
        'python-dotenv',
        'flask'
    ]

    print("\n📦 Installing dependencies...")
    for package in packages:
        print(f"\n  Installing {package}...")
        try:
            subprocess.run(
                ['pip', 'install', package],
                capture_output=True,
                check=True,
                text=True
            )
            print(f"  ✅ {package} installed")
        except subprocess.CalledProcessError as e:
            print(f"  ❌ Failed to install {package}")
            print(f"     Error: {e}")
            return False

    return True


def create_env_file():
    """Guide user to create .env file."""
    print_step(2, "Configure Africa's Talking Credentials")

    print("\n🔑 You need your Africa's Talking API credentials.")
    print("\nIf you DON'T have them yet:")
    print("  1. Go to: https://account.africastalking.com/auth/register")
    print("  2. Sign up (FREE)")
    print("  3. Go to Sandbox mode")
    print("  4. Settings → API Key → Generate")
    print("  5. Come back here with your credentials")

    wait_for_user("\nPress ENTER when you have your API credentials...")

    print("\n📝 Enter your credentials:")

    # Get username
    print("\nUsername (usually 'sandbox' for testing):")
    username = input("  Username: ").strip()
    if not username:
        username = "sandbox"

    # Get API key
    print("\nAPI Key (starts with 'atsk_'):")
    api_key = input("  API Key: ").strip()

    if not api_key:
        print("\n❌ API key is required!")
        return False

    # Create .env file
    env_content = f"""# Africa's Talking API Credentials
# Generated by setup wizard on {time.strftime('%Y-%m-%d %H:%M')}

AFRICASTALKING_USERNAME={username}
AFRICASTALKING_API_KEY={api_key}
SMS_SHORTCODE=22555
"""

    try:
        with open('.env', 'w') as f:
            f.write(env_content)
        print("\n✅ Created .env file with your credentials")
        return True
    except Exception as e:
        print(f"\n❌ Failed to create .env file: {e}")
        return False


def test_connection():
    """Test connection to Africa's Talking."""
    print_step(3, "Test Connection")

    print("\n🧪 Testing connection to Africa's Talking...")

    try:
        # Run test script
        result = subprocess.run(
            ['python', 'scripts/test_sms.py'],
            capture_output=True,
            text=True,
            timeout=30
        )

        if "✅ ALL TESTS PASSED" in result.stdout:
            print("\n✅ Connection test PASSED!")
            print("\nYour setup is working correctly.")
            return True
        else:
            print("\n⚠️  Some tests may have failed.")
            print("\nOutput:")
            print(result.stdout)
            if result.stderr:
                print("\nErrors:")
                print(result.stderr)
            return False
    except FileNotFoundError:
        print("\n❌ Test script not found!")
        print("   Make sure you're in the openresilience directory")
        return False
    except subprocess.TimeoutExpired:
        print("\n❌ Test timed out!")
        return False
    except Exception as e:
        print(f"\n❌ Test failed: {e}")
        return False


