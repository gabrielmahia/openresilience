def main():
    """Main setup wizard."""
    print_header("OpenResilience Kenya - SMS Alert Service Setup Wizard")

    print("\n👋 Welcome! This wizard will help you set up SMS alerts.")
    print("\nWhat you'll need:")
    print("  📧 Email address (for Africa's Talking account)")
    print("  📱 Kenya phone number (for testing)")
    print("  ⏱️  10-15 minutes")

    wait_for_user()

    # Step 1: Check requirements
    print_step(1, "Check Requirements")

    if not check_python():
        return

    if not check_pip():
        return

    # Install dependencies
    if not install_dependencies():
        print("\n❌ Failed to install dependencies!")
        print("   Try manually: pip install africastalking python-dotenv flask")
        return

    # Step 2: Create .env file
    if not create_env_file():
        return

    # Step 3: Test connection
    if not test_connection():
        print("\n⚠️  Connection test had issues, but you can continue...")
        proceed = input("Continue anyway? (yes/no): ").strip().lower()
        if proceed not in ['yes', 'y']:
            return

    # Step 4: Register phone
    register_phone()

    # Step 5: Send test SMS
    send_test_sms()

    # Step 6-8: Explain next steps
    explain_production()
    explain_shortcode()
    explain_webhook()

    # Show summary
    show_next_steps()


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n\n❌ Setup cancelled by user")
        sys.exit(1)
    except Exception as e:
        print(f"\n\n❌ Setup failed: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)
